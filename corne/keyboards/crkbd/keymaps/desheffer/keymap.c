layer_state_t layer_state_set_user(layer_state_t state) {
    // The _SHIFT layer applies a shift modifier to any layers beneath it.
    if (get_highest_layer(state) == _SHIFT) {
        register_code(KC_LSFT);
    } else {
        unregister_code(KC_LSFT);
    }

    return state;
}
